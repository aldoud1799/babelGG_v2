def _norm(value: str) -> str:
    return str(value or '').strip().lower()


def get_language_profile(lang: str) -> AppLanguageProfile:
    return APP_LANGUAGE_PROFILES[normalize_app_language(lang)]


def is_rtl_language(lang: str) -> bool:
    return get_language_profile(lang).rtl


def normalize_app_language(value: str) -> str:
    lang = _norm(value)
    return lang if lang in APP_LANGUAGE_SET else 'english'


def normalize_translation_language(value: str, supported: Iterable[str]) -> str:
    opts = {_norm(v) for v in (supported or []) if _norm(v)}
    if not opts:
        return 'english'
    lang = _norm(value)
    return lang if lang in opts else 'english'


def detect_system_locale_tag() -> str:
    candidates = []
    try:
        candidates.append(locale.getlocale()[0])
    except Exception:
        pass
    if hasattr(locale, 'getdefaultlocale'):
        try:
            candidates.append(locale.getdefaultlocale()[0])
        except Exception:
            pass
    candidates.extend([os.getenv('LC_ALL'), os.getenv('LANG'), os.getenv('LANGUAGE')])

    for raw in candidates:
        if not raw:
            continue
        tag = str(raw).strip().replace('-', '_').lower()
        if tag:
            return tag
    return 'en_us'


def detect_system_language() -> str:
    tag = detect_system_locale_tag()
    short = tag.split('_', 1)[0]
    return _SYSTEM_LOCALE_MAP.get(short, 'english')


def apply_auto_language_preferences(cfg: dict, supported_translation_languages: Iterable[str]) -> dict:
    out = dict(cfg or {})
    out.setdefault('language_auto_detect', True)

    supported = {_norm(v) for v in (supported_translation_languages or []) if _norm(v)}
    if not supported:
        supported = {'english'}

    if bool(out.get('language_auto_detect', True)):
        auto_lang = detect_system_language()
        out['app_language'] = normalize_app_language(auto_lang)
        out['my_language'] = normalize_translation_language(auto_lang, supported)
    else:
        out['app_language'] = normalize_app_language(out.get('app_language', 'english'))
        out['my_language'] = normalize_translation_language(out.get('my_language', 'english'), supported)

    return out


def set_runtime_language(lang: str):
    global _RUNTIME_APP_LANGUAGE
    _RUNTIME_APP_LANGUAGE = normalize_app_language(lang)


def get_runtime_language() -> str:
    return _RUNTIME_APP_LANGUAGE


def tr(key: str, default: str = '', lang: str = None, **kwargs) -> str:
    selected = normalize_app_language(lang or _RUNTIME_APP_LANGUAGE)
    txt = _TRANSLATIONS.get(selected, {}).get(key)
    if txt is None:
        txt = _TRANSLATIONS['english'].get(key, default or key)
    try:
        return str(txt).format(**kwargs) if kwargs else str(txt)
    except Exception:
        return str(txt)
